static void Hash(uint8_t key[STATE_BYTES + TWEAK_BYTES], uint8_t t[TWEAK_BYTES], uint8_t h[STATE_BYTES]) {
    for (int i = STATE_BYTES - 1; i >= 0; i--) {
        h[STATE_BYTES - 1 - i] = 0;
        for (int l = 0; l < 8; l++) {
            uint8_t temp[TWEAK_BYTES] = {0};
            for (int j = 0; j < TWEAK_BYTES; j++) {
                temp[TWEAK_BYTES - 1 - j] = (key[TWEAK_BYTES + i - j] << l) ^ (key[TWEAK_BYTES + i - j - 1] >> (8 - l));
            }
            uint8_t p = 0;
            for (int j = 0; j < TWEAK_BYTES; j++) {
                p ^= (t[j] & temp[j]);
            }
            h[STATE_BYTES - 1 - i] ^= (HW2[p] << l);
        }
    }
}

static void GenerateRoundKey(uint8_t masterKey[KEY_BYTES], uint8_t t[TWEAK_BYTES],
                             uint8_t rk[RK_ROUNDS][STATE_BYTES],
                             uint8_t w[2][STATE_BYTES],
                             uint8_t h[2][STATE_BYTES]) {
    uint8_t keyPrime[KEY_BYTES] = {0};
    for (int i = 0; i < KEY_BYTES; i++) {
        for (int j = 0; j < 8; j++) {
            keyPrime[i] ^= ((masterKey[(11 * (8 * i + j) % (KEY_BYTES * 8)) / 8] >> ((11 * (8 * i + j) % (KEY_BYTES * 8)) % 8)) & 1) << j;
        }
    }
    for (int i = 0; i < STATE_BYTES; i++) {
        w[0][i] = masterKey[i];
        w[1][i] = masterKey[i + STATE_BYTES];
        for (int j = 0; j < RK_ROUNDS; j++) {
            rk[j][i] = masterKey[i + (j + 2) * STATE_BYTES];
        }
    }
    uint8_t hk[2][STATE_BYTES + TWEAK_BYTES];
    for (int i = STATE_BYTES + TWEAK_BYTES - 1; i >= 0; i--) {
        if (i > 0) {
            hk[0][i] = (keyPrime[i] << 1) ^ (keyPrime[i - 1] >> 7);
            hk[1][i] = (keyPrime[i + STATE_BYTES + TWEAK_BYTES] << 2) ^ (keyPrime[i + STATE_BYTES + TWEAK_BYTES - 1] >> 6);
        } else {
            hk[0][i] = keyPrime[i] << 1;
            hk[1][i] = ((keyPrime[i + STATE_BYTES + TWEAK_BYTES] << 2) ^ (keyPrime[i + STATE_BYTES + TWEAK_BYTES - 1] >> 6)) & 0xfe;
        }
    }
    Hash(hk[0], t, h[0]);
    Hash(hk[1], t, h[1]);
}

// ============================================================================
// Core round application (single round, no I/O)
// ============================================================================
static void apply_single_round(uint8_t state[STATE_BYTES],
                               uint8_t rk[RK_ROUNDS][STATE_BYTES],
                               uint8_t h[2][STATE_BYTES],
                               int round) {
    uint8_t h_xor[STATE_BYTES];
    for (int i = 0; i < STATE_BYTES; i++) {
        h_xor[i] = h[0][i] ^ h[1][i];
    }

    if (round >= 1 && round <= RA) {
        int r = round - 1;
        SubBytes(state);
        MixColumns(state);
        AddRoundKey(state, rk[r]);
        AddRoundConstant(state, ROUND_CONST[r]);
        Permutation(state);
    }
    else if (round == RA + 1) {
        SubBytes(state);
        MixColumns(state);
        AddRoundKey(state, h[0]);
        Permutation(state);
    }
    else if (round >= RA + 2 && round <= RA + RB + 1) {
        int r = round - (RA + 2);
        SubBytes(state);
        MixColumns(state);
        AddRoundKey(state, rk[RA + r]);
        AddRoundConstant(state, ROUND_CONST[RA + r]);
        Permutation(state);
    }
    else if (round == RA + RB + 2) {
        SubBytes(state);
        MixColumns(state);
        AddRoundKey(state, h_xor);
    }
    else if (round == RA + RB + 3) {
        SubBytes(state);
    }
    else if (round >= RA + RB + 4 && round <= RA + 2*RB + 3) {
        int r = round - (RA + RB + 4);
        InvPermutation(state);
        AddRoundConstant(state, ROUND_CONST_Prime[r]);
        AddRoundKey(state, rk[r]);
        MixColumns(state);
        SubBytes(state);
    }
    else if (round == RA + 2*RB + 4) {
        InvPermutation(state);
        AddRoundKey(state, h[1]);
        MixColumns(state);
        SubBytes(state);
    }
    else if (round >= RA + 2*RB + 5 && round <= TOTAL_ROUNDS) {
        int r = round - (RA + 2*RB + 5);
        InvPermutation(state);
        AddRoundConstant(state, ROUND_CONST_Prime[r + RB]);
        AddRoundKey(state, rk[r + RB]);
        MixColumns(state);
        SubBytes(state);
    }
}

// ============================================================================
// Range application (no I/O)
// ============================================================================
static void apply_round_slice(uint8_t state[STATE_BYTES],
                              uint8_t rk[RK_ROUNDS][STATE_BYTES],
                              uint8_t w[2][STATE_BYTES],
                              uint8_t h[2][STATE_BYTES],
                              int first_round, int last_round) {
#ifndef SKIP_WHITENING
    if (first_round == 1) {
        Whitening(state, w[0]);
    }
#endif
    for (int round = first_round; round <= last_round; round++) {
        apply_single_round(state, rk, h, round);
    }
#ifndef SKIP_WHITENING
    if (last_round == TOTAL_ROUNDS) {
        Whitening(state, w[1]);
    }
#endif
}

