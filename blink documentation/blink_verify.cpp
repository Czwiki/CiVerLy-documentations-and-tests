static void SubBytes(uint8_t state[STATE_BYTES]) {
    for (int i = 0; i < STATE_BYTES; i++) {
        uint8_t hi = SBOX[state[i] >> 4];
        uint8_t lo = SBOX[state[i] & 0xF];
        state[i] = (hi << 4) | lo;
    }
}

static void MixColumns(uint8_t state[STATE_BYTES]) {
    for (int col = 0; col < STATE_NIBBLES / 4; col++) {
        uint8_t coldata[4];
        for (int r = 0; r < 4; r++) {
            int idx = col + r * (STATE_NIBBLES / 4);
            int byteIndex = idx / 2;
            bool highNibble = (idx % 2 == 1);
            uint8_t nibble = highNibble ? (state[byteIndex] >> 4) : (state[byteIndex] & 0xF);
            coldata[r] = nibble;
        }
        uint8_t result[4] = {0};
        for (int r = 0; r < 4; r++) {
            for (int c = 0; c < 4; c++) {
                result[r] ^= M_MATRIX[r][c] ? coldata[c] : 0;
            }
        }
        for (int r = 0; r < 4; r++) {
            int idx = col + r * (STATE_NIBBLES / 4);
            int byteIndex = idx / 2;
            bool highNibble = (idx % 2 == 1);
            if (highNibble) {
                state[byteIndex] = (result[r] << 4) | (state[byteIndex] & 0xF);
            } else {
                state[byteIndex] = (state[byteIndex] & 0xF0) | result[r];
            }
        }
    }
}

